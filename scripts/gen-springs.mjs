// Converts the Framer spring transitions used on the site into CSS `linear()` easings.
// Each spring becomes a pair of custom properties: --spring-<name> (easing) and --spring-<name>-d (duration).
// Usage: node scripts/gen-springs.mjs  ->  writes src/styles/springs.css
import { writeFileSync } from 'node:fs';

// name: [stiffness, damping, mass]
const SPRINGS = {
  '500-60': [500, 60, 1], // component variant changes (nav, buttons, cards)
  '400-30': [400, 30, 1], // hover lift effects
  '170-25': [170, 25, 1], // appear / scroll-in effects
  '300-30': [300, 30, 1],
  '400-40': [400, 40, 1],
  '200-30': [200, 30, 1],
  '300-40': [300, 40, 1],
  '500-40': [500, 40, 1],
  '820-60': [820, 60, 1], // ghost buttons, project cards
  '200-40': [200, 40, 1], // per-character text reveal
  '247-25': [246.7, 25.1, 1], // duration 0.4s / bounce 0.2 spring (project card appear)
  '580-50': [580, 50, 1], // spotlight scroll smoothing
  '213-33': [213, 33, 1], // album cover hover
};

export function spring([stiffness, damping, mass], step = 1 / 240) {
  // Semi-implicit Euler integration of x'' = -k(x-1) - c x'
  let x = 0;
  let v = 0;
  let t = 0;
  const points = [[0, 0]];
  while (t < 10) {
    const a = (-stiffness * (x - 1) - damping * v) / mass;
    v += a * step;
    x += v * step;
    t += step;
    points.push([t, x]);
    if (Math.abs(x - 1) < 0.0005 && Math.abs(v) < 0.005) break;
  }
  return { duration: t, points };
}

export function toLinear(points, duration, samples = 40) {
  const out = [];
  for (let i = 0; i <= samples; i++) {
    const t = (i / samples) * duration;
    const idx = Math.min(points.length - 1, Math.round(t / (duration / (points.length - 1))));
    const value = i === samples ? 1 : points[idx][1];
    out.push(`${+value.toFixed(4)} ${+((i / samples) * 100).toFixed(1)}%`);
  }
  return `linear(${out.join(', ')})`;
}

let css = '/* Generated by scripts/gen-springs.mjs — Framer spring transitions as CSS easings. */\n:root {\n';
for (const [name, params] of Object.entries(SPRINGS)) {
  const { duration, points } = spring(params);
  css += `  --spring-${name}: ${toLinear(points, duration)};\n  --spring-${name}-d: ${Math.round(duration * 1000)}ms;\n`;
}
css += '}\n';
writeFileSync('src/styles/springs.css', css);
